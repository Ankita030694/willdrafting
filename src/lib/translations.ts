/**
 * Clean up bilingual parenthetical strings from text
 * e.g. "Distribute Your Assets (संपत्ति का बंटवारा)" -> "Distribute Your Assets" (in EN)
 * or -> "अपनी संपत्ति का बंटवारा करें" (in HI)
 */
export function sanitizeBilingual(text: string, isHi: boolean): string {
  if (!text) return text;
  const trimmed = text.trim();

  // If in Hindi, check if we have a direct dictionary match
  if (isHi) {
    if (translationsMap[trimmed]) return translationsMap[trimmed];
    // If pattern is "English (Hindi)" -> return Hindi
    const match = trimmed.match(/\(([\u0900-\u097F\s\/\.,\-\d]+)\)/);
    if (match && match[1]) {
      return match[1].trim();
    }
  } else {
    // If in English, strip any Hindi text inside parentheses or standalone
    return trimmed
      .replace(/\s*\([\u0900-\u097F\s\/\.,\-\d]+\)/g, "")
      .replace(/[\u0900-\u097F]+/g, "")
      .replace(/\s{2,}/g, " ")
      .trim();
  }

  return trimmed;
}

/**
 * High-performance DOM Translator Engine
 * Dynamically ensures that when Hindi is selected, everything is pure Hindi,
 * and when English is selected, everything is pure English with zero mixed Hindi.
 */
export function applyLanguageTranslation(root: HTMLElement, isHi: boolean) {
  if (!root) return;

  const reverseMap: Record<string, string> = {};
  Object.entries(translationsMap).forEach(([en, hi]) => {
    reverseMap[hi] = en;
  });

  const translateString = (str: string): string => {
    const trimmed = str.trim();
    if (!trimmed) return str;

    if (isHi) {
      // 1. Direct dictionary match
      if (translationsMap[trimmed]) {
        return str.replace(trimmed, translationsMap[trimmed]);
      }

      // 2. If it has "(Hindi Text)" inside, use the Hindi text
      const parenMatch = trimmed.match(/^(.+?)\s*\(([\u0900-\u097F\s\/\.,\-\d]+)\)$/);
      if (parenMatch && parenMatch[2]) {
        return parenMatch[2].trim();
      }

      // 3. Dynamic patterns:
      // "Asset X of Y" -> "संपत्ति X / Y"
      const assetMatch = trimmed.match(/^Asset\s+(\d+)\s+of\s+(\d+)$/i);
      if (assetMatch) {
        return `संपत्ति ${assetMatch[1]} / ${assetMatch[2]}`;
      }

      // "Step X of Y" -> "चरण X / Y"
      const stepMatch = trimmed.match(/^Step\s+(\d+)\s+of\s+(\d+)(.*)$/i);
      if (stepMatch) {
        return `चरण ${stepMatch[1]} / ${stepMatch[2]}${stepMatch[3] ? ` • ${translationsMap[stepMatch[3].replace(/^[\s•]+/, "").trim()] || stepMatch[3]}` : ""}`;
      }

      // "List Mode (X)" -> "सूची मोड (X)"
      const listMatch = trimmed.match(/^List\s+Mode\s*\((\d+)\)$/i);
      if (listMatch) {
        return `सूची मोड (${listMatch[1]})`;
      }

      // "X Registered" -> "X पंजीकृत"
      const regMatch = trimmed.match(/^(\d+)\s+Registered$/i);
      if (regMatch) {
        return `${regMatch[1]} पंजीकृत`;
      }

      // "X assets selected" -> "X संपत्तियां चुनी गईं"
      const selMatch = trimmed.match(/^(\d+)\s+assets?\s+selected$/i);
      if (selMatch) {
        return `${selMatch[1]} संपत्तियां चुनी गईं`;
      }

      // "X gets 100%" -> "X को 100% मिलता है"
      const getsMatch = trimmed.match(/^(.+?)\s+gets\s+(\d+)%$/i);
      if (getsMatch) {
        return `${getsMatch[1]} को ${getsMatch[2]}% मिलता है`;
      }

      // "Needs X% more" -> "X% और आवंटित करें"
      const needsMatch = trimmed.match(/^Needs\s+(\d+)%\s+more$/i);
      if (needsMatch) {
        return `${needsMatch[1]}% और आवंटित करें`;
      }

      // "Same as last: X" -> "पिछले जैसा: X"
      if (trimmed.startsWith("Same as last:")) {
        return trimmed.replace("Same as last:", "पिछले जैसा:");
      }

      // "Tip: ..."
      if (trimmed.startsWith("Tip:")) {
        return trimmed
          .replace("Tip:", "सुझाव:")
          .replace("Press number keys", "चुनने के लिए संख्या कुंजी")
          .replace("to pick", "दबाएं")
          .replace("to continue", "आगे बढ़ने के लिए")
          .replace("for same as last", "पिछले जैसा रखने के लिए");
      }

      // Common single-word translations
      const words = ["Spouse", "Daughter", "Son", "Father", "Mother", "Brother", "Sister", "Other"];
      for (const w of words) {
        if (trimmed.toLowerCase() === w.toLowerCase() && translationsMap[w]) {
          return translationsMap[w];
        }
      }
    } else {
      // In English mode, revert any known Hindi back to English
      if (reverseMap[trimmed]) {
        return str.replace(trimmed, reverseMap[trimmed]);
      }
      // Strip any residual Hindi in parentheses like "Distribute (संपत्ति का बंटवारा)" -> "Distribute"
      const cleaned = trimmed
        .replace(/\s*\([\u0900-\u097F\s\/\.,\-\d]+\)/g, "")
        .replace(/\s{2,}/g, " ")
        .trim();
      if (cleaned && cleaned !== trimmed) {
        return str.replace(trimmed, cleaned);
      }
    }

    return str;
  };

  // Walk text nodes
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT, {
    acceptNode(node) {
      // Don't translate inside script or style
      const parentTag = node.parentElement?.tagName;
      if (parentTag === "SCRIPT" || parentTag === "STYLE" || parentTag === "CODE") {
        return NodeFilter.FILTER_REJECT;
      }
      // Don't alter the language toggle pill itself so it always displays "English" and "हिंदी"
      if (node.parentElement?.closest(".language-toggle-pill")) {
        return NodeFilter.FILTER_REJECT;
      }
      return NodeFilter.FILTER_ACCEPT;
    },
  });

  const textNodes: Text[] = [];
  let current = walker.nextNode();
  while (current) {
    textNodes.push(current as Text);
    current = walker.nextNode();
  }

  textNodes.forEach((node) => {
    const val = node.nodeValue || "";
    const updated = translateString(val);
    if (updated !== val) {
      node.nodeValue = updated;
    }
  });

  // Also translate input placeholders
  const inputs = root.querySelectorAll<HTMLInputElement>("input, textarea");
  inputs.forEach((input) => {
    const ph = input.getAttribute("placeholder");
    if (ph) {
      const updatedPh = translateString(ph);
      if (updatedPh !== ph) {
        input.setAttribute("placeholder", updatedPh);
      }
    }
  });
}

